package com.reactnative.bleperipheral

import android.util.Base64
import android.util.Log
import com.facebook.react.bridge.Arguments
import com.facebook.react.bridge.Promise
import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.bridge.ReadableMap
import com.facebook.react.bridge.WritableMap
import com.reactnative.bleperipheral.gatt.AttStatus
import com.reactnative.bleperipheral.gatt.BleUuid
import com.reactnative.bleperipheral.gatt.CharacteristicPermission
import com.reactnative.bleperipheral.gatt.CharacteristicProperty
import com.reactnative.bleperipheral.gatt.GattCharacteristic
import com.reactnative.bleperipheral.gatt.GattService
import com.reactnative.bleperipheral.peripheral.BlePeripheral
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.cancel
import kotlinx.coroutines.launch

/**
 * Thin bridge between JS and [BlePeripheral]: parses arguments, calls the peripheral, settles
 * promises and forwards [PeripheralEvent]s. NativeRNBlePeripheralSpec is generated by codegen
 * from src/NativeRNBlePeripheral.ts into this same package, so it needs no import.
 */
class RnBlePeripheralModule(reactContext: ReactApplicationContext) :
    NativeRNBlePeripheralSpec(reactContext) {

    private val scope = CoroutineScope(SupervisorJob() + Dispatchers.Default)
    private val peripheral = BlePeripheral(reactContext, scope)

    init {
        scope.launch { peripheral.events.collect { dispatch(it) } }
    }

    override fun getName(): String = NAME

    override fun invalidate() {
        peripheral.release()
        scope.cancel()
        super.invalidate()
    }

    // --- Lifecycle ----------------------------------------------------------------------

    override fun start(promise: Promise) = launchPromise(promise) { peripheral.start() }

    override fun stop(promise: Promise) = launchPromise(promise) { peripheral.stop() }

    // --- Services -----------------------------------------------------------------------

    override fun addService(service: ReadableMap, promise: Promise) = launchPromise(promise) {
        peripheral.addService(parseService(service))
    }

    override fun removeService(uuid: String, promise: Promise) = launchPromise(promise) {
        peripheral.removeService(BleUuid.parse(uuid))
    }

    override fun removeAllServices(promise: Promise) = launchPromise(promise) {
        peripheral.removeAllServices()
    }

    // --- Advertising --------------------------------------------------------------------

    override fun startAdvertising(options: ReadableMap, promise: Promise) = launchPromise(promise) {
        val uuids = options.stringList("serviceUuids").map { BleUuid.parse(it) }
        peripheral.startAdvertising(options.optString("name"), uuids)
    }

    override fun stopAdvertising(promise: Promise) = launchPromise(promise) { peripheral.stopAdvertising() }

    override fun isAdvertising(promise: Promise) = launchPromise(promise) { peripheral.isAdvertising }

    // --- Data ---------------------------------------------------------------------------

    override fun notify(
        serviceUuid: String,
        characteristicUuid: String,
        value: String,
        deviceId: String?,
        promise: Promise,
    ) = launchPromise(promise) {
        peripheral.notify(BleUuid.parse(serviceUuid), BleUuid.parse(characteristicUuid), decode(value), deviceId)
    }

    override fun respond(requestId: String, status: String, value: String?) {
        try {
            peripheral.respond(requestId, AttStatus.fromJs(status), value?.let { decode(it) })
        } catch (e: IllegalArgumentException) {
            Log.w(TAG, "Invalid respond() arguments, answering with an error instead", e)
            peripheral.respond(requestId, AttStatus.UNLIKELY_ERROR, null)
        }
    }

    // --- State --------------------------------------------------------------------------

    override fun getState(promise: Promise) = launchPromise(promise) { peripheral.currentState() }

    override fun getConnectedDevices(promise: Promise) = launchPromise(promise) {
        Arguments.fromList(peripheral.connectedDevices())
    }

    // --- Events -> JS -------------------------------------------------------------------

    private fun dispatch(event: PeripheralEvent) {
        try {
            when (event) {
                is PeripheralEvent.ReadRequest -> emitOnReadRequest(map {
                    putString("requestId", event.requestId)
                    putString("deviceId", event.deviceId)
                    putString("serviceUuid", event.serviceUuid.toString())
                    putString("characteristicUuid", event.characteristicUuid.toString())
                })
                is PeripheralEvent.WriteRequest -> emitOnWriteRequest(map {
                    putString("requestId", event.requestId)
                    putString("deviceId", event.deviceId)
                    putString("serviceUuid", event.serviceUuid.toString())
                    putString("characteristicUuid", event.characteristicUuid.toString())
                    putString("value", encode(event.value))
                    putBoolean("responseNeeded", event.responseNeeded)
                })
                is PeripheralEvent.Subscribed -> emitOnSubscribed(map {
                    putString("deviceId", event.deviceId)
                    putString("serviceUuid", event.serviceUuid.toString())
                    putString("characteristicUuid", event.characteristicUuid.toString())
                    putString("mode", event.mode)
                })
                is PeripheralEvent.Unsubscribed -> emitOnUnsubscribed(map {
                    putString("deviceId", event.deviceId)
                    putString("serviceUuid", event.serviceUuid.toString())
                    putString("characteristicUuid", event.characteristicUuid.toString())
                })
                is PeripheralEvent.DeviceConnected -> emitOnDeviceConnected(map {
                    putString("deviceId", event.deviceId)
                })
                is PeripheralEvent.DeviceDisconnected -> emitOnDeviceDisconnected(map {
                    putString("deviceId", event.deviceId)
                })
                is PeripheralEvent.MtuChanged -> emitOnMtuChanged(map {
                    putString("deviceId", event.deviceId)
                    putInt("mtu", event.mtu)
                })
                is PeripheralEvent.StateChanged -> emitOnStateChanged(map {
                    putString("state", event.state)
                })
            }
        } catch (e: Exception) {
            Log.w(TAG, "Could not emit ${event::class.simpleName} to JS", e)
        }
    }

    private inline fun map(block: WritableMap.() -> Unit): WritableMap =
        Arguments.createMap().apply(block)

    // --- Promise plumbing ---------------------------------------------------------------

    private fun launchPromise(promise: Promise, block: suspend () -> Any?) {
        scope.launch {
            try {
                val result = block()
                promise.resolve(if (result == Unit) null else result)
            } catch (e: CancellationException) {
                throw e
            } catch (e: BleException) {
                promise.reject(e.code, e.message, e)
            } catch (e: IllegalArgumentException) {
                promise.reject(ErrorCodes.INVALID_ARGUMENT, e.message, e)
            } catch (e: SecurityException) {
                promise.reject(ErrorCodes.PERMISSION, e.message, e)
            } catch (e: Exception) {
                promise.reject(ErrorCodes.INTERNAL, e.message, e)
            }
        }
    }

    // --- Parsing ------------------------------------------------------------------------

    private fun parseService(map: ReadableMap): GattService {
        val characteristics = map.getArray("characteristics")?.let { array ->
            (0 until array.size()).map { i ->
                parseCharacteristic(array.getMap(i) ?: throw IllegalArgumentException("characteristics[$i] is null"))
            }
        }.orEmpty()

        return GattService(
            uuid = BleUuid.parse(map.getString("uuid") ?: throw IllegalArgumentException("Service uuid is required")),
            primary = map.optBoolean("primary", true),
            characteristics = characteristics,
            includedServiceUuids = map.stringList("includedServiceUuids").map { BleUuid.parse(it) },
        )
    }

    private fun parseCharacteristic(map: ReadableMap) = GattCharacteristic(
        uuid = BleUuid.parse(map.getString("uuid") ?: throw IllegalArgumentException("Characteristic uuid is required")),
        properties = map.stringList("properties").map { CharacteristicProperty.fromJs(it) }.toSet(),
        permissions = map.stringList("permissions").map { CharacteristicPermission.fromJs(it) }.toSet(),
        initialValue = map.optString("value")?.let { decode(it) },
        dynamicRead = map.optBoolean("dynamicRead", false),
        dynamicWrite = map.optBoolean("dynamicWrite", false),
    )

    private fun ReadableMap.optString(key: String): String? =
        if (hasKey(key) && !isNull(key)) getString(key) else null

    private fun ReadableMap.optBoolean(key: String, default: Boolean): Boolean =
        if (hasKey(key) && !isNull(key)) getBoolean(key) else default

    private fun ReadableMap.stringList(key: String): List<String> {
        if (!hasKey(key) || isNull(key)) return emptyList()
        val array = getArray(key) ?: return emptyList()
        return (0 until array.size()).mapNotNull { array.getString(it) }
    }

    private fun decode(base64: String): ByteArray = Base64.decode(base64, Base64.DEFAULT)

    private fun encode(bytes: ByteArray): String = Base64.encodeToString(bytes, Base64.NO_WRAP)

    companion object {
        const val NAME = "RNBlePeripheral"
        private const val TAG = "RNBlePeripheral"
    }
}
